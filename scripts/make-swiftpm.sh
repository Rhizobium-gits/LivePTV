#!/bin/sh
# 🐱 Build a Swift Playgrounds app package (dist/LivePTV.swiftpm + .zip) from the sources, so the app can be
# 🐱 built and run on the iPad itself without Xcode. All library targets are merged into one module.
set -e
cd "$(dirname "$0")/.."
OUT=dist/LivePTV.swiftpm
rm -rf "$OUT" dist/LivePTV.swiftpm.zip
mkdir -p "$OUT/App"
for m in CameraKit PTVCore Pipeline LivePTVUI; do
  (cd LivePTVKit/Sources/$m && find . -name "*.swift") | while read -r f; do
    mkdir -p "$OUT/App/$m/$(dirname "$f")"
    # 🐱 one module: drop the imports of our own modules
    grep -v -E '^import (CameraKit|PTVCore|Pipeline|LivePTVUI)$' "LivePTVKit/Sources/$m/$f" > "$OUT/App/$m/$f"
  done
done
cat > "$OUT/App/LivePTVApp.swift" <<'SWIFT'
import SwiftUI

// 🐱 Swift Playgrounds entry point. Swift Playgrounds has no Bundle.module, so the camera Wi-Fi details are
// 🐱 compiled in (CameraPresetLocal.swift, generated from App/Camera.local.plist).
@main
struct LivePTVApp: App {
    @StateObject private var model = AppModel(preset: bundledCameraPreset ?? CameraPreset.load())

    var body: some Scene {
        WindowGroup {
            RootView(model: model)
        }
    }
}
SWIFT
# 🐱 camera preset as Swift source (this package is only for your own iPad; dist/ is git-ignored)
python3 -I - App/Camera.local.plist "$OUT/App/CameraPresetLocal.swift" <<'PY'
import os, plistlib, sys
src, dst = sys.argv[1], sys.argv[2]
def lit(v):
    s = str(v)
    if any(ord(c) < 32 for c in s): raise SystemExit("control characters in " + repr(s))
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
line = "let bundledCameraPreset: CameraPreset? = nil"
if os.path.exists(src):
    d = plistlib.load(open(src, "rb"))
    if d.get("SSID"):
        mac = d.get("MACAddress")
        line = ("let bundledCameraPreset: CameraPreset? = CameraPreset(ssid: %s, password: %s, macAddress: %s, host: %s, port: %s)"
                % (lit(d["SSID"]), lit(d.get("Password", "")),
                   ("CameraPreset.normalizeMAC(%s)" % lit(mac)) if mac else "nil",
                   lit(d["Host"]) if d.get("Host") else "nil", str(int(d["Port"])) if d.get("Port") else "nil"))
open(dst, "w").write("// 🐱 Generated by scripts/make-swiftpm.sh from App/Camera.local.plist.\n" + line + "\n")
PY
cat > "$OUT/Package.swift" <<'SWIFT'
// swift-tools-version: 5.9

// 🐱 Swift Playgrounds app package for LivePTV (generated by scripts/make-swiftpm.sh).
import PackageDescription
import AppleProductTypes

let package = Package(
    name: "LivePTV",
    platforms: [
        .iOS("17.0")
    ],
    products: [
        .iOSApplication(
            name: "LivePTV",
            targets: ["AppModule"],
            bundleIdentifier: "local.liveptv.playgrounds",
            teamIdentifier: "",
            displayVersion: "0.1",
            bundleVersion: "1",
            appIcon: .placeholder(icon: .camera),
            accentColor: .presetColor(.blue),
            supportedDeviceFamilies: [
                .pad
            ],
            supportedInterfaceOrientations: [
                .portrait,
                .landscapeRight,
                .landscapeLeft,
                .portraitUpsideDown(.when(deviceFamilies: [.pad]))
            ],
            capabilities: [
                .camera(purposeString: "Used only when a USB camera is selected as the video source."),
                .localNetwork(purposeString: "LivePTV connects directly to the camera on its own Wi-Fi network. Video never leaves this iPad.")
            ]
        )
    ],
    targets: [
        .executableTarget(
            name: "AppModule",
            path: ".",
            exclude: ["Package.swift"]
        )
    ]
)
SWIFT
(cd dist && zip -qr LivePTV.swiftpm.zip LivePTV.swiftpm)
echo "created $OUT and dist/LivePTV.swiftpm.zip"
